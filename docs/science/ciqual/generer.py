"""Generates apps/server/db/migrations/0007_ciqual.sql from the official Ciqual 2020 table.

Source: Anses. 2020. Table de composition nutritionnelle des aliments Ciqual (French version),
https://doi.org/10.5281/zenodo.4770600, file « Table Ciqual 2020_FR_2020 07 07.xls », CC BY 4.0.
Kept per 100 g: energy (EU regulation 1169/2011, else N x Jones factor with fibres), proteins
(N x Jones factor), carbohydrates, fat, fibres. « traces » and « < x » become 0; foods without
energy are left out. Usage: python -I generer.py <path to the .xls> (needs pandas and xlrd).
"""
import io
import math
import sys
from pathlib import Path

import pandas as pd

OUT = Path(__file__).parents[3] / 'apps' / 'server' / 'db' / 'migrations' / '0007_ciqual.sql'


def num(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return None
    s = str(v).strip().replace(',', '.')
    if s in ('-', ''):
        return None
    if s.lower() == 'traces' or s.startswith('<'):
        return 0.0
    try:
        return float(s)
    except ValueError:
        return None


def main(path):
    df = pd.read_excel(path)
    c = df.columns
    rows = []
    for _, r in df.iterrows():
        name = str(r[c[7]]).strip()
        kcal = num(r[c[10]])
        if kcal is None:
            kcal = num(r[c[12]])
        if kcal is None or not name or name == 'nan':
            continue
        rows.append((str(int(r[c[6]])), name, kcal, num(r[c[14]]) or 0, num(r[c[16]]) or 0, num(r[c[17]]) or 0, num(r[c[26]]) or 0))

    def q(s):
        return "'" + s.replace("'", "''") + "'"

    def n(x):
        return ('%.2f' % x).rstrip('0').rstrip('.')

    out = io.StringIO()
    out.write(
        "-- Ciqual 2020 (ANSES), French food composition table: energy (EU 1169/2011) and macronutrients\n"
        "-- per 100 g. Licence CC BY 4.0 / Etalab: cite « Anses. 2020. Table de composition nutritionnelle\n"
        "-- des aliments Ciqual ». Generated by docs/science/ciqual/generer.py from the official file.\n"
        "alter table aliment add column if not exists code_ciqual text;\n"
        "create unique index if not exists aliment_ciqual_code on aliment (code_ciqual) where source = 'ciqual';\n"
        "alter table aliment no force row level security;\n"
        "insert into aliment (source, code_ciqual, nom, kcal100, proteines100, glucides100, lipides100, fibres100) values\n"
    )
    out.write(',\n'.join(f"('ciqual', {q(code)}, {q(nm)}, {n(k)}, {n(p)}, {n(g)}, {n(l)}, {n(f)})" for code, nm, k, p, g, l, f in rows))
    out.write("\non conflict (code_ciqual) where source = 'ciqual' do nothing;\nalter table aliment force row level security;\n")
    OUT.write_text(out.getvalue(), encoding='utf-8', newline='\n')
    print(len(rows), 'aliments ->', OUT)


if __name__ == '__main__':
    main(sys.argv[1])
